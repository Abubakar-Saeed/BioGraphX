"""
Feature Names Registry
================================================================================

Author: Abubakar Saeed
Created: January 2026
Last Modified: February 2026

Description:
    Centralized registry of all feature names generated by the BioGraphX
    pipeline. This module defines the complete 157-dimensional feature space
    with explicit naming conventions for each feature category.

    The feature space is organized into five distinct categories that capture
    complementary aspects of protein sequence and structure:

    1. BASIC_GRAPH_NAMES (85 features):
       Topological properties of residue interaction graphs including node/edge
       statistics, degree distributions, centrality measures, community
       structure, and localization patterns.

    2. HYBRID_FEATURE_NAMES (22 features):
       Enrichment scores for synergistic combinations of non-covalent
       interactions (e.g., salt bridge + hydrogen bond) that represent
       cooperative biochemical networks.

    3. SIGNAL_FEATURE_NAMES (20 features):
       Subcellular localization evidence combining sequence motif detection
       and hybrid interaction enrichment for 10 cellular compartments.

    4. PHYSICS_NAMES (19 features):
       Global physicochemical properties including isoelectric point, charge,
       hydrophobicity (GRAVY), autocorrelation periodicities, and sequence
       complexity metrics.

    5. FRUSTRATION_FEATURE_NAMES (11 features):
       Configurational frustration metrics quantifying local constraint
       satisfaction and energy landscape ruggedness.


Notes on Distance Metrics:
    IMPORTANT: All distance-derived features in graph topology (path lengths,
    diameter, radius) are computed on graphs where edge constraints are defined
    by LINEAR SEQUENCE DISTANCE thresholds. These features represent connectivity
    patterns in primary structure space, NOT Euclidean proximity in tertiary
    structure. This distinction is critical when interpreting features such as
    "Avg_Shortest_Path" and "Graph_Diameter".

================================================================================
"""

