def get_feature_category(category: str) -> List[str]:
    """
    Retrieve feature names for a specific analytical category.

    Parameters
    ----------
    category : str
        One of: 'basic_graph', 'hybrid', 'targeting_signal', 'signal',
        'profile', 'physics', 'frustration'

    Returns
    -------
    List[str]
        Feature names belonging to the specified category.

    Raises
    ------
    KeyError
        If category is not recognized.
    """
    if category == 'basic_graph':
        return BASIC_GRAPH_NAMES
    elif category == 'hybrid':
        return HYBRID_FEATURE_NAMES
    elif category in {'targeting_signal', 'signal', 'profile'}:
        return TARGETING_SIGNAL_NAMES
    elif category == 'physics':
        return PHYSICS_NAMES
    elif category == 'frustration':
        return FRUSTRATION_FEATURE_NAMES
    else:
        raise KeyError(
            f"Unknown feature category: {category}. "
            f"Valid categories: ['basic_graph', 'hybrid', 'targeting_signal', 'signal', 'profile', 'physics', 'frustration']"
        )


